#!/usr/bin/env python3
"""aligned.npz -> GR00T N1.7 dataset (LeRobot v2.1 + modality.json + umi_modality_config.py).

  python3 to_gr00t.py cup     # data/cup -> ~/datasets/cup (--out to change); absolute and ~/ paths as is

state/action per hand: <hand>_eef = xyz + rot6d (9), <hand>_gripper = 0 open .. 1 closed (1); action = next frame, absolute.
gripper action = trigger command, not position (a grasped object stalls the fingers, so position would never squeeze).
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
from collections import Counter

import cv2
import numpy as np
from scipy.spatial.transform import Rotation

from umi import episode as io
from umi.align import (ALIGNED_VERSION, DEFAULT_ACTION_HORIZON, calib_hash, rot6d,
                       state_names, trim_valid)

CHUNK = 1000

CONFIG_TEMPLATE = '''"""GR00T N1.7 modality config, generated by to_gr00t.py.

train (in Isaac-GR00T): uv run python gr00t/experiment/launch_finetune.py --base-model-path nvidia/GR00T-N1.7-3B \\
    --dataset-path {dataset} --embodiment-tag NEW_EMBODIMENT \\
    --modality-config-path {dataset}/umi_modality_config.py --output-dir <output dir>
"""
from gr00t.configs.data.embodiment_configs import register_modality_config
from gr00t.data.embodiment_tags import EmbodimentTag
from gr00t.data.types import (
    ActionConfig,
    ActionFormat,
    ActionRepresentation,
    ActionType,
    ModalityConfig,
)

HANDS = {hands!r}
VIDEO_KEYS = {video_keys!r}
ACTION_HORIZON = {horizon}   # {horizon_s:.2f}s @ {fps}fps. on change GR00T recomputes stats (older GR00T: delete meta/stats.json, relative_stats.json)

state_keys = []
action_configs = []
for h in HANDS:
    state_keys += [h + "_eef", h + "_gripper"]
    action_configs += [
        ActionConfig(rep=ActionRepresentation.RELATIVE, type=ActionType.EEF,
                     format=ActionFormat.XYZ_ROT6D, state_key=h + "_eef"),
        # gripper: trigger command
        ActionConfig(rep=ActionRepresentation.ABSOLUTE, type=ActionType.NON_EEF,
                     format=ActionFormat.DEFAULT, state_key=h + "_gripper"),
    ]

umi_config = {{
    "video": ModalityConfig(delta_indices=[0], modality_keys=VIDEO_KEYS),
    "state": ModalityConfig(delta_indices=[0], modality_keys=state_keys),
    "action": ModalityConfig(
        delta_indices=list(range(ACTION_HORIZON)),
        modality_keys=state_keys,
        action_configs=action_configs,
    ),
    "language": ModalityConfig(delta_indices=[0], modality_keys=["annotation.human.task_description"]),
}}

register_modality_config(umi_config, embodiment_tag=EmbodimentTag.NEW_EMBODIMENT)
'''


def ep_layout(cfg, hands=None):
    hs = hands or cfg.get("hands") or ["left", "right"]
    return tuple(h for h in ("left", "right") if h in hs), tuple(sorted(cfg.get("cameras") or {}))


def load_aligned(ep_dir):
    with np.load(os.path.join(ep_dir, "aligned.npz")) as z:
        return {k: z[k] for k in z.files}


def state_ranges(hands):
    out = {}
    for k, h in enumerate(hands):
        out[h + "_eef"] = (10 * k, 10 * k + 9)
        out[h + "_gripper"] = (10 * k + 9, 10 * k + 10)
    return out


def build_state(al, hands, s, e, grip="grip_"):
    """grip: "grip_" measured position (state) | "grip_cmd_" trigger command (action)"""
    parts = []
    for h in hands:
        T = al["T_" + h][s:e]
        parts += [T[:, :3, 3], rot6d(T[:, :3, :3]), al[grip + h][s:e, None]]
    return np.concatenate(parts, axis=1).astype(np.float32)


def video_frames(ep, cam, idxs, shortest_edge):
    """resized BGR frames for idxs (a repeated idx reuses the previous frame)"""
    r = io.FrameReader(ep, cam)
    try:
        last, img = None, None
        for i in idxs:
            if i != last:
                raw = r.get(i)
                if raw is None:
                    raise RuntimeError("failed to read video frame: %s (corrupt or missing)" % r.describe(int(i)))
                last, img = i, resize_keep_aspect(raw, shortest_edge)
            yield img
    finally:
        r.close()


def first_frame(ep, cam, idx, shortest_edge):
    return next(video_frames(ep, cam, [idx], shortest_edge))


def resize_keep_aspect(img, shortest_edge):
    if not shortest_edge:
        return img
    h, w = img.shape[:2]
    s = float(shortest_edge) / min(h, w)
    nw, nh = int(round(w * s / 2) * 2), int(round(h * s / 2) * 2)   # libx264 yuv420p needs even size
    return cv2.resize(img, (nw, nh), interpolation=cv2.INTER_AREA)


def check_aspect(plan, cams, skipped):
    """skip episodes whose aspect ratio differs from the majority (resize would distort)"""
    if not plan:
        return plan
    aspect = {}
    for ep, _, _, first in plan:
        for c in cams:
            h, w = first_frame(ep, c, first[c], 0).shape[:2]
            aspect[ep, c] = (round(w / float(h), 2), "%dx%d" % (w, h))
    ref = {c: Counter(aspect[p[0], c][0] for p in plan).most_common(1)[0][0] for c in cams}
    keep = []
    for p in plan:
        bad = ["%s %s" % (c, aspect[p[0], c][1]) for c in cams if aspect[p[0], c][0] != ref[c]]
        if bad:
            skipped.append((os.path.basename(p[0]), "different aspect ratio %s (reference w/h %s)" % (", ".join(bad), ref)))
        else:
            keep.append(p)
    return keep


def write_video(path, frames_iter, fps, size_hw):
    h, w = size_hw
    os.makedirs(os.path.dirname(path), exist_ok=True)
    cmd = ["ffmpeg", "-loglevel", "error", "-y",
           "-f", "rawvideo", "-pix_fmt", "bgr24", "-s", "%dx%d" % (w, h), "-r", str(fps), "-i", "-",
           "-c:v", "libx264", "-pix_fmt", "yuv420p", "-preset", "veryfast", "-crf", "20",
           "-g", "2",            # short GOP: fast random frame access in training
           path]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)
    n = 0
    try:
        for f in frames_iter:
            if f.shape[:2] != (h, w):
                f = cv2.resize(f, (w, h), interpolation=cv2.INTER_AREA)
            proc.stdin.write(np.ascontiguousarray(f).tobytes())
            n += 1
    except BaseException:
        proc.kill()
        proc.wait()
        raise
    proc.stdin.close()
    if proc.wait() != 0:
        raise RuntimeError("ffmpeg failed: %s" % path)
    return n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("data_root", nargs="?", default="",
                    help="folder under data/ (e.g. cup); absolute or ~ paths as is. default: data/")
    ap.add_argument("--out", help="dataset output path (must not exist, or use --overwrite). default: ~/datasets/<data folder name>")
    ap.add_argument("--overwrite", action="store_true")
    ap.add_argument("--shortest-edge", type=int, default=256,
                    help="video shortest edge (GR00T N1.7 default preprocessing shortest_image_edge=256). 0 = original")
    ap.add_argument("--action-horizon", type=int, default=DEFAULT_ACTION_HORIZON)
    ap.add_argument("--hands", nargs="+", choices=["left", "right"],
                    help="dataset hand layout (default: the layout of most episodes)")
    args = ap.parse_args()

    if shutil.which("ffmpeg") is None:
        sys.exit("ffmpeg not found: sudo apt install ffmpeg")
    root = io.data_path(args.data_root)
    out = os.path.abspath(os.path.expanduser(args.out or os.path.join("~/datasets", os.path.basename(root)))).rstrip("/\\")
    if os.path.exists(out):
        if not args.overwrite:
            sys.exit("%s already exists (--overwrite)" % out)
        if os.listdir(out) and not os.path.exists(os.path.join(out, "meta", "info.json")):
            sys.exit("%s is not a dataset folder (no meta/info.json) -> not overwriting" % out)

    import pyarrow as pa
    import pyarrow.parquet as papq

    eps = io.list_episodes(root)
    if not eps:
        sys.exit("no episodes: %s" % root)
    cur = io.load_current_config()

    metas = {ep: io.load_meta(ep) for ep in eps}
    usable = [m["config"] for m in metas.values() if m["config"].get("cameras") and m.get("origin")]
    layouts = Counter(ep_layout(c) for c in usable)
    if args.hands:
        want_hands = ep_layout({}, args.hands)[0]
        layouts = Counter({k: v for k, v in layouts.items() if k[0] == want_hands})
    if not layouts:
        sys.exit("no convertible episodes (with cameras%s)" % (", hands %s" % list(args.hands) if args.hands else ""))
    ref = layouts.most_common(1)[0][0]
    hands, cams = list(ref[0]), list(ref[1])
    if len(layouts) > 1:
        print("[info] %d hand/camera layouts %s -> using %s / %s (choose with --hands)"
              % (len(layouts), dict(layouts), hands, cams))
    plan, skipped, missing, stale = [], [], [], []
    for ep in eps:
        name = os.path.basename(ep)
        ecfg = metas[ep]["config"]
        if not ecfg.get("cameras"):
            skipped.append((name, "no cameras (component test)"))
            continue
        if ep_layout(ecfg) != ref:
            skipped.append((name, "hand/camera layout %s / %s != reference %s / %s" % (ep_layout(ecfg) + ref)))
            continue
        p = os.path.join(ep, "aligned.npz")
        if not os.path.exists(p):
            missing.append(name)
            continue
        with np.load(p) as z:
            ver = int(z["format_version"])
            if ver != ALIGNED_VERSION:
                stale.append((name, "format v%d != v%d" % (ver, ALIGNED_VERSION)))
                continue
            if str(z["calib_hash"]) != calib_hash(io.effective_config(ecfg, cur, bool(z["current_mount"]))):
                stale.append((name, "calibration (align/gripper_model/latency_ms) changed after alignment"))
                continue
            valid, ep_fps, origin_mode = z["valid"], z["fps"], str(z["origin_mode"])
            frame_idx = {c: z["frame_" + c] for c in cams}
        if origin_mode != "calib":
            skipped.append((name, "no origin"))
            continue
        s, e, holes = trim_valid(valid)
        if holes or e - s < args.action_horizon:
            skipped.append((name, "%d invalid inside / usable length %d" % (holes, e - s)))
            continue
        fps = int(round(float(ep_fps)))   # same in all: align.fps is in calib_hash
        plan.append((ep, s, e, {c: int(frame_idx[c][s]) for c in cams}))
    if missing:
        sys.exit("%d without aligned.npz (not aligned or failed): %s\n-> run `python3 check_episode.py %s` and retry."
                 " For episodes that keep failing, fix the cause or append _DISCARDED to the folder name"
                 % (len(missing), ", ".join(missing), args.data_root))
    if stale:
        sys.exit("%d need re-alignment: %s\n-> run `python3 check_episode.py %s` and retry"
                 " (with --use-current-mount if you aligned with it before)"
                 % (len(stale), "; ".join("%s (%s)" % x for x in stale), args.data_root))
    plan = check_aspect(plan, cams, skipped)
    for name, why in skipped:
        print("[skip] %s  (%s)" % (name, why))
    if not plan:
        sys.exit("no episodes to convert")
    print("converting %d, skipped %d (hands %s, cameras %s)" % (len(plan), len(skipped), hands, cams))

    tmp = out + ".tmp"
    if os.path.exists(tmp):
        shutil.rmtree(tmp)
    try:
        total_frames = convert(args, plan, metas, hands, cams, fps, tmp, out, pa, papq)
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    if os.path.exists(out):
        shutil.rmtree(out)
    os.rename(tmp, out)
    print("saved %d episodes, %d frames → %s" % (len(plan), total_frames, out))
    print("modality config: %s" % os.path.join(out, "umi_modality_config.py"))


def convert(args, plan, metas, hands, cams, fps, root, final_path, pa, papq):
    """write plan into root (temp dir) -> total frames. final_path is what the generated config refers to"""
    tasks, episodes = {}, []
    total_frames, video_hw = 0, {}
    ranges = state_ranges(hands)
    T0 = {h: [] for h in hands}

    for ep_idx, (ep, s, e, _) in enumerate(plan):
        meta = metas[ep]
        al = load_aligned(ep)
        for h in hands:
            T0[h].append(al["T_" + h][s])
        n = e - s
        state = build_state(al, hands, s, e)
        cmd = build_state(al, hands, s, e, grip="grip_cmd_")
        action = np.concatenate([cmd[1:], cmd[-1:]], axis=0)       # action[t] = cmd[t+1], last repeated
        task = meta["task"]
        t_idx = tasks.setdefault(task, len(tasks))

        chunk = ep_idx // CHUNK
        for c in cams:
            key = "observation.images.%s_wrist" % c
            idxs = al["frame_" + c][s:e]
            if c not in video_hw:   # same aspect guaranteed by check_aspect; later episodes are just resized
                video_hw[c] = first_frame(ep, c, idxs[0], args.shortest_edge).shape[:2]
            frames = video_frames(ep, c, idxs, args.shortest_edge)
            nv = write_video(os.path.join(root, "videos", "chunk-%03d" % chunk, key,
                                          "episode_%06d.mp4" % ep_idx), frames, fps, video_hw[c])
            assert nv == n, "video frames (%d) != data length (%d)" % (nv, n)

        vec = pa.list_(pa.float32())
        table = pa.table({
            "observation.state": pa.array([r.tolist() for r in state], type=vec),
            "action": pa.array([r.tolist() for r in action], type=vec),
            "timestamp": (np.arange(n) / float(fps)).astype(np.float32),
            "frame_index": np.arange(n, dtype=np.int64),
            "episode_index": np.full(n, ep_idx, dtype=np.int64),
            "index": np.arange(total_frames, total_frames + n, dtype=np.int64),
            "task_index": np.full(n, t_idx, dtype=np.int64),
            "next.done": np.r_[np.zeros(n - 1, bool), True],
        })
        pq = os.path.join(root, "data", "chunk-%03d" % chunk, "episode_%06d.parquet" % ep_idx)
        os.makedirs(os.path.dirname(pq), exist_ok=True)
        papq.write_table(table, pq)

        episodes.append({"episode_index": ep_idx, "tasks": [task], "length": n,
                         "source": os.path.basename(ep)})
        total_frames += n
        print("[ok] %s → episode %d  (%d frames, task=%r)" % (os.path.basename(ep), ep_idx, n, task))
    ep_idx = len(plan)

    names = state_names(hands)
    features = {
        "action": {"dtype": "float32", "shape": [len(names)], "names": names},
        "observation.state": {"dtype": "float32", "shape": [len(names)], "names": names},
    }
    for c in cams:
        vh, vw = video_hw[c]
        features["observation.images.%s_wrist" % c] = {
            "dtype": "video", "shape": [vh, vw, 3], "names": ["height", "width", "channels"],
            "info": {"video.height": vh, "video.width": vw, "video.codec": "h264",
                     "video.pix_fmt": "yuv420p", "video.is_depth_map": False, "video.fps": fps,
                     "video.channels": 3, "has_audio": False}}
    for k, dt in [("timestamp", "float32"), ("frame_index", "int64"), ("episode_index", "int64"),
                  ("index", "int64"), ("task_index", "int64"), ("next.done", "bool")]:
        features[k] = {"dtype": dt, "shape": [1], "names": None}

    info = {
        "codebase_version": "v2.1",
        "robot_type": "umi_" + "_".join(hands),
        "total_episodes": ep_idx,
        "total_frames": total_frames,
        "total_tasks": len(tasks),
        "total_videos": ep_idx * len(cams),
        "total_chunks": (ep_idx - 1) // CHUNK + 1,
        "chunks_size": CHUNK,
        "fps": fps,
        "splits": {"train": "0:%d" % ep_idx},
        "data_path": "data/chunk-{episode_chunk:03d}/episode_{episode_index:06d}.parquet",
        "video_path": "videos/chunk-{episode_chunk:03d}/{video_key}/episode_{episode_index:06d}.mp4",
        "features": features,
    }
    modality = {
        "state": {k: {"start": a, "end": b} for k, (a, b) in ranges.items()},
        "action": {k: {"start": a, "end": b} for k, (a, b) in ranges.items()},
        "video": {"%s_wrist" % c: {"original_key": "observation.images.%s_wrist" % c} for c in cams},
        "annotation": {"human.task_description": {"original_key": "task_index"}},
    }
    # start_pose.json: mean episode-start TCP (xyz + rot6d) = pose the robot moves to before running the policy
    start = {h: np.r_[np.mean([T[:3, 3] for T in T0[h]], 0),
                      rot6d(Rotation.from_matrix([T[:3, :3] for T in T0[h]]).mean().as_matrix())].round(4).tolist() for h in hands}
    meta_dir = os.path.join(root, "meta")
    os.makedirs(meta_dir, exist_ok=True)
    task_rows = [{"task_index": i, "task": t} for t, i in sorted(tasks.items(), key=lambda x: x[1])]
    for name, data in (("info.json", info), ("modality.json", modality),
                       ("episodes.jsonl", episodes), ("tasks.jsonl", task_rows), ("start_pose.json", start)):
        with open(os.path.join(meta_dir, name), "w", encoding="utf-8") as f:
            if name.endswith(".json"):
                json.dump(data, f, indent=4)
            else:
                f.writelines(json.dumps(r, ensure_ascii=False) + "\n" for r in data)
    with open(os.path.join(root, "umi_modality_config.py"), "w", encoding="utf-8") as f:
        f.write(CONFIG_TEMPLATE.format(
            dataset=final_path, hands=hands,
            video_keys=["%s_wrist" % c for c in cams], horizon=args.action_horizon,
            horizon_s=args.action_horizon / float(fps), fps=fps))
    return total_frames


if __name__ == "__main__":
    main()
